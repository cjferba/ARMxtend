# -*- coding: utf-8 -*-
"""
VizARM: transformation of association rules into a typed directed graph, following the VizARE methodology of:

    Fernandez-Basso, C., Ruiz, M.D., Molina-Solana, M., Martin-Bautista, M.J.
    (2026). "VizARE: An Intermediate Representation to Support the
    Visualization of Association Rules in Data Mining". Future Internet,
    18(7), 374. https://doi.org/10.3390/fi18070374

Unlike an item-to-item graph (where an edge would directly join each item of the antecedent with each item of the
consequent, losing the structure of the rule as soon as it has more than one item per side), VizARE models the graph
with TWO types of node -- item and rule -- and connects them with directed edges with an explicit semantic role:
antecedent (item -> rule) and consequent (rule -> item). This makes it possible to represent unambiguously rules with
several items in the antecedent and/or the consequent (Section 4.1, Algorithm 1 of the paper), and stores the
interest measures (support, confidence, lift, ...) as attributes of the rule node itself, not of the edge.

Besides the typed graph, this module implements:
    * The optional summary layer (Section 4.2): "summary" nodes that group equivalent rules according to a signature
      (same antecedent, same consequent, or the antecedent->consequent pair), aggregating their measures (count, min,
      max, mean, quantiles) to be able to explore large sets of rules without losing traceability to the original
      rules (`members`).
    * Export to the JSON Graph Format (JGF), the intermediate format proposed in the paper (Section 3.3.3 and 4), as
      well as GraphML and DOT (formats already supported by tools such as Gephi/Cytoscape/Graphviz/NetworkX, also
      mentioned in Section 4.4 of the paper).
    * An interactive, self-contained HTML viewer (`AREtoGraph.to_html`) and the export to Neo4j (`to_cypher`) and
      MongoDB (`to_documents`) described in Section 4.3.

@author Carlos Fernandez-Basso
"""
import csv
import json
import math
from pathlib import Path
from typing import Dict

import networkx as nx
import numpy as np

from ..ARM.meta_rules import rule_key

_VALID_SIGNATURES = ("antecedent", "consequent", "antecedent_consequent")


def _default_item_group(item):
    """
    Default group of an item: the name of the attribute if the item follows the 'attribute_label' convention (Section
    4.1: "Item nodes encode atomic attribute-value pairs using the normalized syntax attribute_value"), the same one
    used by the columns generated by `preprocessing.FuzzyLib.Fuzzification`; otherwise, the item itself.
    """
    return item.split("_", 1)[0] if "_" in item else item


def _sanitize_for_export(value):
    """GraphML/DOT do not admit lists as attribute values; we serialize them as text."""
    if isinstance(value, (list, tuple, set, frozenset)):
        return ";".join(str(v) for v in value)
    return value


def _json_safe(value):
    """Convert numpy scalars to native types and NaN/inf to None, so that the JSON is valid in JavaScript."""
    if isinstance(value, np.generic):
        value = value.item()
    if isinstance(value, float) and not math.isfinite(value):
        return None
    if isinstance(value, dict):
        return {str(key): _json_safe(item) for key, item in value.items()}
    if isinstance(value, (list, tuple, set, frozenset)):
        return [_json_safe(item) for item in value]
    return value


def _embed_json(obj):
    """JSON safe to embed inside a <script> tag (it escapes '<' so that '</script>' does not close the tag)."""
    return json.dumps(_json_safe(obj)).replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")


def _cypher_string(value):
    return "'" + str(value).replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n") + "'"


def _cypher_value(value):
    value = _json_safe(value)
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, list):
        return "[" + ", ".join(_cypher_value(item) for item in value) + "]"
    return _cypher_string(value)


class AREtoGraph(object):
    """
    Build the typed graph (item/rule/summary) of a set of association rules, following the VizARE methodology (see
    module).
    """

    def __init__(self, path=None, MeasuresRules=None, MeasuresItems=None,
                 SepRule=";", SepFI=";", SepItems=","):
        """
        Args:
            path (str, optional): path to a CSV file of association rules, with columns 'antecedents' and
                'consequents' (items concatenated with `SepItems`), plus one column per measure indicated in
                `MeasuresRules`. If omitted, an empty object is built to be populated with `add_rule`/
                `add_rules_from_dataframe`
            MeasuresRules (list[str], optional): names of the measures of the rules (e.g.
                ['support', 'confidence', 'lift']) that will be included as attributes of each 'rule' node
            MeasuresItems (list[str], optional): names of the measures of the frequent itemsets (e.g. ['support']), if
                they are loaded separately with `load_item_measures`
            SepRule (str): field separator of the rules CSV
            SepFI (str): field separator of the frequent-itemsets CSV
            SepItems (str): separator between items inside the same side (antecedent/consequent) of a rule
        """
        self.MeasuresRules = list(MeasuresRules) if MeasuresRules else ["support", "confidence"]
        self.MeasuresItems = list(MeasuresItems) if MeasuresItems else []
        self.SepRule = SepRule
        self.SepFI = SepFI
        self.SepItems = SepItems
        self.graph: nx.DiGraph = nx.DiGraph()

        if path:
            self.load_rules(path)

    @classmethod
    def from_dataframe(cls, rules_df, rule_measures=("support", "confidence", "lift"), item_group_fn=None):
        """
        Build the graph directly from a pandas.DataFrame of rules, in the same format returned by
        `ARM.association_rules` or `FIM.FARE.fuzzy_association_rules` (columns 'antecedents', 'consequents' with
        frozensets of items, plus one column per measure).

        Args:
            rules_df (pandas.DataFrame): association rules
            rule_measures (Iterable[str]): columns of `rules_df` to include as attributes of each 'rule' node
            item_group_fn (callable[str] -> str, optional): see `add_rule`

        Returns:
            An AREtoGraph instance with the graph already built
        """
        instance = cls(MeasuresRules=list(rule_measures))
        instance.add_rules_from_dataframe(rules_df, rule_measures, item_group_fn=item_group_fn)
        return instance

    def add_rules_from_dataframe(self, rules_df, rule_measures=None, item_group_fn=None):
        """Add to the graph one rule (Algorithm 1) for each row of `rules_df`."""
        measures = list(rule_measures) if rule_measures is not None else self.MeasuresRules
        for _, rule in rules_df.iterrows():
            antecedent = sorted(rule["antecedents"])
            consequent = sorted(rule["consequents"])
            measureValues = {measure: float(rule[measure]) for measure in measures if measure in rule}
            self.add_rule(antecedent, consequent, measureValues, item_group_fn=item_group_fn)

    def add_rule(self, antecedent, consequent, measures=None, rule_id=None, item_group_fn=None):
        """
        Algorithm 1 (RulesToGraph) of Fernandez-Basso et al. (2026): add a rule as a 'rule' node (with its interest
        measures as its own attributes) connected by directed edges to the 'item' nodes of its antecedent
        (relation='antecedent') and its consequent (relation='consequent').

        Args:
            antecedent (Iterable[str]): items of the antecedent of the rule
            consequent (Iterable[str]): items of the consequent of the rule
            measures (dict[str, float], optional): interest measures of the rule (support, confidence, lift, certainty
                factor, ...), stored as attributes of the 'rule' node
            rule_id (str, optional): identifier of the rule node; by default generated with `ARM.meta_rules.rule_key`
            item_group_fn (callable[str] -> str, optional): function that computes the 'group' attribute of an item
                node (by default, `_default_item_group`: the prefix before '_', as in 'temperature_cold' ->
                'temperature')

        Returns:
            The identifier of the rule node added
        """
        antecedent = sorted(antecedent)
        consequent = sorted(consequent)
        measures = dict(measures) if measures else {}
        item_group_fn = item_group_fn or _default_item_group

        if rule_id is None:
            rule_id = "rule::{}".format(rule_key(antecedent, consequent))

        self.graph.add_node(
            rule_id, kind="rule", name="{} -> {}".format(
                self.SepItems.join(antecedent), self.SepItems.join(consequent)),
            group="rule", **measures)

        for item in antecedent:
            self._add_item_node(item, item_group_fn)
            self.graph.add_edge(item, rule_id, relation="antecedent")
        for item in consequent:
            self._add_item_node(item, item_group_fn)
            self.graph.add_edge(rule_id, item, relation="consequent")

        return rule_id

    def _add_item_node(self, item, item_group_fn):
        if item not in self.graph:
            self.graph.add_node(item, kind="item", name=item, group=item_group_fn(item))

    def summarize(self, signature="antecedent_consequent", measures=None, quantiles=(0.25, 0.5, 0.75)):
        """
        Summary layer (Section 4.2 of the paper): add to the graph one 'summary' node for each group of equivalent
        rules under the indicated signature, aggregating their interest measures. The summary nodes are connected to
        the SAME item nodes, with the same semantic direction (antecedent/consequent) as the rule nodes, so the
        resulting graph contains both layers (rule by rule and summarized) for the visualization tool to choose the
        granularity.

        Args:
            signature (str): 'antecedent' (groups by the same set of antecedent items), 'consequent' (same
                consequent) or 'antecedent_consequent' (same antecedent->consequent pair, default)
            measures (Iterable[str], optional): measures of the 'rule' nodes to aggregate (by default,
                `self.MeasuresRules`)
            quantiles (Iterable[float]): additional quantiles to compute per measure (Section 4.2: "optional
                quantiles")

        Returns:
            list[str]: the identifiers of the summary nodes created
        """
        if signature not in _VALID_SIGNATURES:
            raise ValueError("signature debe ser uno de {}, recibido: {}".format(_VALID_SIGNATURES, signature))
        measures = list(measures) if measures is not None else self.MeasuresRules

        groups: Dict[tuple, dict] = {}
        for node, data in self.graph.nodes(data=True):
            if data.get("kind") != "rule":
                continue

            antecedentItems = tuple(sorted(
                source for source, _, edgeData in self.graph.in_edges(node, data=True)
                if edgeData.get("relation") == "antecedent"))
            consequentItems = tuple(sorted(
                target for _, target, edgeData in self.graph.out_edges(node, data=True)
                if edgeData.get("relation") == "consequent"))

            if signature == "antecedent":
                key = antecedentItems
            elif signature == "consequent":
                key = consequentItems
            else:
                key = (antecedentItems, consequentItems)

            group = groups.setdefault(key, {
                "ruleIds": [], "antecedent": antecedentItems, "consequent": consequentItems})
            group["ruleIds"].append(node)

        summaryIds = []
        for index, group in enumerate(groups.values()):
            summaryId = "summary::{}::{}".format(signature, index)
            stats: Dict[str, float] = {"rule_count": len(group["ruleIds"])}

            for measure in measures:
                found = [self.graph.nodes[ruleId][measure] for ruleId in group["ruleIds"]
                         if measure in self.graph.nodes[ruleId]]
                if not found:
                    continue
                values = np.asarray(found, dtype=float)
                stats["{}_min".format(measure)] = float(values.min())
                stats["{}_max".format(measure)] = float(values.max())
                stats["{}_mean".format(measure)] = float(values.mean())
                for quantile in quantiles:
                    stats["{}_q{}".format(measure, int(round(quantile * 100)))] = float(np.quantile(values, quantile))

            self.graph.add_node(
                summaryId, kind="summary", name="summary({})[{}]".format(signature, len(group["ruleIds"])),
                group="summary", signature=signature, members=list(group["ruleIds"]), **stats)

            for item in group["antecedent"]:
                self.graph.add_edge(item, summaryId, relation="antecedent")
            for item in group["consequent"]:
                self.graph.add_edge(summaryId, item, relation="consequent")

            summaryIds.append(summaryId)

        return summaryIds

    def load_rules(self, path):
        """
        Load association rules from a CSV with columns 'antecedents' and 'consequents' (items separated by
        `SepItems`), plus one column per measure of `MeasuresRules`, adding them to the graph with `add_rule`.
        """
        with open(path, newline="") as ruleFile:
            reader = csv.DictReader(ruleFile, delimiter=self.SepRule)
            for row in reader:
                antecedent = row["antecedents"].split(self.SepItems)
                consequent = row["consequents"].split(self.SepItems)
                measures = {measure: float(row[measure]) for measure in self.MeasuresRules if measure in row}
                self.add_rule(antecedent, consequent, measures)

    def load_item_measures(self, path):
        """
        Load measures of individual itemsets (e.g. support) from a CSV with an 'itemset' column and one per measure of
        `MeasuresItems`, and add them as attributes of the corresponding item nodes.
        """
        with open(path, newline="") as itemFile:
            reader = csv.DictReader(itemFile, delimiter=self.SepFI)
            for row in reader:
                itemset = row["itemset"]
                if itemset not in self.graph:
                    continue
                for measure in self.MeasuresItems:
                    if measure in row:
                        self.graph.nodes[itemset][measure] = float(row[measure])

    def _selected_graph(self, max_rules=None, sort_by=None):
        """
        The whole graph or, if `max_rules` is given, a subgraph with only the `max_rules` rules with the highest
        `sort_by` (by default, the first measure of `MeasuresRules` that the rules have), their items, and the summary
        nodes with some of those rules as a member (with `members` reduced to those that are kept).
        """
        if max_rules is None:
            return self.graph

        ruleNodes = [(node, data) for node, data in self.graph.nodes(data=True) if data.get("kind") == "rule"]
        measure = sort_by or next(
            (m for m in self.MeasuresRules if any(m in data for _, data in ruleNodes)), None)
        if measure is not None:
            ruleNodes.sort(key=lambda item: item[1].get(measure, float("-inf")), reverse=True)
        keptRules = {node for node, _ in ruleNodes[:max_rules]}

        keep = set(keptRules)
        for node, data in self.graph.nodes(data=True):
            if data.get("kind") == "summary" and keptRules.intersection(data.get("members", [])):
                keep.add(node)
        for node in list(keep):
            keep.update(self.graph.predecessors(node))
            keep.update(self.graph.successors(node))

        subgraph = self.graph.subgraph(keep).copy()
        for node, data in subgraph.nodes(data=True):
            if data.get("kind") == "summary":
                data["members"] = [m for m in data["members"] if m in keptRules]
                data["rule_count"] = len(data["members"])
        return subgraph

    @staticmethod
    def _jgf_from(graph):
        nodes = {}
        for node, data in graph.nodes(data=True):
            metadata = {key: _json_safe(value) for key, value in data.items() if key not in ("name",)}
            nodes[node] = {"label": data.get("name", node), "metadata": metadata}

        edges = [
            {"source": source, "target": target, "relation": data.get("relation"), "metadata": {}}
            for source, target, data in graph.edges(data=True)
        ]

        return {"graph": {"directed": True, "type": "association-rules", "nodes": nodes, "edges": edges}}

    def to_jgf_dict(self):
        """
        Serialize the graph to the intermediate format proposed in the paper: JSON Graph Format (JGF, see Section
        3.3.3 and 4.1), as a Python dict ready for `json.dumps` or to insert directly into a document database
        (MongoDB) or graph database (Neo4j), as described in Section 4.3.

        Returns:
            dict with the structure {'graph': {'directed': True, 'nodes':
            {id: {'label', 'metadata': {...}}}, 'edges': [{'source',
            'target', 'relation', 'metadata'}]}}
        """
        return self._jgf_from(self.graph)

    def to_jgf(self, indent=2):
        """Serialize the graph to a JSON string in JGF format (see `to_jgf_dict`)."""
        return json.dumps(self.to_jgf_dict(), indent=indent)

    def to_html(self, path=None, title="ARMxtend - VizARE", max_rules=None, sort_by=None, measure=None,
                min_value=None):
        """
        Generate an INTERACTIVE, self-contained HTML viewer of the VizARE graph: a single file with no external
        dependencies (no CDN or network) that opens in any browser and embeds the graph itself in JGF format
        (`to_jgf_dict`), so that the viewer consumes exactly the intermediate representation proposed in the paper.

        The viewer offers: automatic force-directed layout, zoom, panning and dragging of nodes (pin/release with a
        double click), tooltip and detail panel (readable rule and all its measures), node search, filter by minimum
        value of a measure, size and color of the rules according to the chosen measure, and toggling of the item,
        rule and summary layers (see `summarize`). Hovering or selecting a node highlights its neighbors.

        Args:
            path (str | os.PathLike, optional): if given, the HTML is written to that file
            title (str): title of the page
            max_rules (int, optional): for large sets, keep only the `max_rules` rules with the highest `sort_by`
                (with their items); the viewer is smooth up to a few thousand nodes
            sort_by (str, optional): measure to choose those rules (by default, the first of `MeasuresRules`)
            measure (str, optional): initial measure for size/color and filter
            min_value (float, optional): initial minimum value of `measure`

        Returns:
            str: the HTML content
        """
        template = (Path(__file__).parent / "viewer_template.html").read_text(encoding="utf-8")
        data = _embed_json(self._jgf_from(self._selected_graph(max_rules, sort_by)))
        options = _embed_json({"measure": measure, "min_value": min_value})
        escapedTitle = (str(title).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))
        html = (template.replace("__TITLE__", escapedTitle)
                .replace("__OPTIONS__", options).replace("__DATA__", data))

        if path is not None:
            Path(path).write_text(html, encoding="utf-8")
        return html

    def to_cypher(self, max_rules=None, sort_by=None):
        """
        Cypher statements (Neo4j) that create the graph: one `:Item`, `:Rule` or `:Summary` node per node (with all
        its attributes as properties) and one `:ANTECEDENT` (item -> rule) or `:CONSEQUENT` (rule -> item)
        relationship per edge (Section 4.3 of the paper). The identifiers are stored in the `id` property.

        Args: see `to_html` for `max_rules` and `sort_by`.

        Returns:
            str: statements separated by ';' and line breaks, ready for `cypher-shell` or the Neo4j browser
        """
        graph = self._selected_graph(max_rules, sort_by)
        labels = {"item": "Item", "rule": "Rule", "summary": "Summary"}
        lines = []
        for node, data in graph.nodes(data=True):
            properties = {"id": node, "name": data.get("name", node)}
            properties.update({key: value for key, value in data.items() if key not in ("name",)})
            body = ", ".join("{}: {}".format(key, _cypher_value(value)) for key, value in properties.items())
            lines.append("CREATE (:{} {{{}}});".format(labels.get(data.get("kind"), "Node"), body))
        for source, target, data in graph.edges(data=True):
            relation = "ANTECEDENT" if data.get("relation") == "antecedent" else "CONSEQUENT"
            lines.append("MATCH (a {{id: {}}}), (b {{id: {}}}) CREATE (a)-[:{}]->(b);".format(
                _cypher_string(source), _cypher_string(target), relation))
        return "\n".join(lines)

    def to_documents(self, max_rules=None, sort_by=None):
        """
        Flat documents ready to insert into a document database such as MongoDB (`collection.insert_many`), Section 4.3
        of the paper: a collection of nodes, with `_id` = node id, `name`, `kind`, `group` and the measures as
        top-level fields (so they can be indexed and filtered, e.g. `{"kind": "rule", "confidence": {"$gte": 0.8}}`),
        and a collection of edges with `source`, `target` and `relation`.

        Args: see `to_html` for `max_rules` and `sort_by`.

        Returns:
            dict {'nodes': [...], 'edges': [...]}
        """
        graph = self._selected_graph(max_rules, sort_by)
        nodes = []
        for node, data in graph.nodes(data=True):
            document = {"_id": node, "name": data.get("name", node)}
            document.update({key: _json_safe(value) for key, value in data.items() if key != "name"})
            nodes.append(document)
        edges = [{"source": source, "target": target, "relation": data.get("relation")}
                 for source, target, data in graph.edges(data=True)]
        return {"nodes": nodes, "edges": edges}

    def exportGraph(self, type=0):
        """
        Export the built graph.

        Args:
            type (int): 0 -> JGF string (JSON Graph Format, the intermediate format proposed by Fernandez-Basso et
                al., 2026, exportable to MongoDB/Neo4j or to libraries such as D3.js/Bokeh); 1 -> string in GraphML
                format (Gephi/Cytoscape/NetworkX); 2 -> string in DOT format (Graphviz); 3 -> the underlying
                networkx.DiGraph object

        Returns:
            A text string (JGF/GraphML/DOT) or the networkx graph, depending on `type`
        """
        if type == 0:
            return self.to_jgf()
        elif type == 1:
            return "\n".join(nx.generate_graphml(self._sanitized_graph()))
        elif type == 2:
            return self._to_dot()
        elif type == 3:
            return self.graph
        else:
            raise ValueError(
                "type debe ser 0 (JGF), 1 (GraphML), 2 (DOT) o 3 (networkx.DiGraph), recibido: {}".format(type))

    def _sanitized_graph(self):
        """Copy of the graph with list-type attributes serialized as text (GraphML does not admit lists)."""
        sanitized = self.graph.copy()
        for _, data in sanitized.nodes(data=True):
            for key, value in list(data.items()):
                data[key] = _sanitize_for_export(value)
        return sanitized

    def _to_dot(self):
        """Escritor DOT minimo, sin dependencias adicionales a networkx."""
        lines = ["digraph ARM {"]
        for node, data in self.graph.nodes(data=True):
            label = data.get("name", node)
            lines.append('    "{}" [kind="{}", label="{}"];'.format(node, data.get("kind", ""), label))
        for source, target, attributes in self.graph.edges(data=True):
            attrText = ", ".join(
                '{}="{}"'.format(key, _sanitize_for_export(value)) for key, value in attributes.items())
            label = " [{}]".format(attrText) if attrText else ""
            lines.append('    "{}" -> "{}"{};'.format(source, target, label))
        lines.append("}")
        return "\n".join(lines)
